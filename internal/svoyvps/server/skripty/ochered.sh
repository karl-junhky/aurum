# Очередь интерфейса $dev, общее для установки и сноса: Go ставит этот кусок
# перед каждым из них, и оба одинаково решают, чей корень. Корень с нулевым
# номером ставит ядро по default_qdisc. Пересадка - замена корня на pfifo и
# его снятие - заставляет ядро поставить свой заново, как после
# перезагрузки: снять корень с нулевым номером tc не даёт. Корень с
# ненулевым номером ставил человек (cake с ограничением скорости и подобное),
# его параметры не восстановить. Исключение - pfifo при отметке
# $otm/peresadka: его оставила наша пересадка, у которой не прошло снятие
# корня. Отметка кладётся до замены корня и уходит после снятия, так что
# pfifo человека с нашим не путается.

# ochered печатает очереди $dev, koren_iz - корень из них: «fq_codel 0:».
# tc на 20.04 не понимает «root» в показе, корень берётся из полного вывода
# по четвёртому полю: строка mq может кончаться на «root», и поиск « root »
# с пробелами её бы не нашёл.
ochered() { tc qdisc show dev "$dev" 2>/dev/null || true; }
koren_iz() { awk '$4 == "root" { print $2, $3; exit }' <<<"$1"; }

# ubrat_ustarevshuyu_otmetku <корень>: отметка годна, только пока корень -
# оставленный ею pfifo. Корень не прочитан - отметка остаётся.
ubrat_ustarevshuyu_otmetku() {
    if [ -n "$1" ] && { [ "${1%% *}" != pfifo ] || [ "${1#* }" = "0:" ]; }; then
        rm -f -- "$otm/peresadka"
    fi
}

# koren_ruchnoy <корень>: корень, прочитанный непустым, поставил человек.
koren_ruchnoy() { [ "${1#* }" != "0:" ] && { [ "${1%% *}" != pfifo ] || [ ! -e "$otm/peresadka" ]; }; }

# peresadit пересаживает очередь $dev. Код 1: отметка не записалась, корень
# не тронут. 2: замена не прошла, корень прежний. 3: снятие не прошло, корень
# pfifo при отметке.
peresadit() {
    { : > "$otm/peresadka"; } 2>/dev/null || return 1
    if ! tc qdisc replace dev "$dev" root pfifo 2>/dev/null; then
        rm -f -- "$otm/peresadka"
        return 2
    fi
    tc qdisc del dev "$dev" root 2>/dev/null || return 3
    # Не снявшуюся отметку уберёт следующий проход: корень уже не pfifo.
    rm -f -- "$otm/peresadka"
    return 0
}
